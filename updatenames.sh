# Durch alle JSON-Dateien im Zielverzeichnis iterieren
find "$TARGET_DIR" -type f -name "*.json" | while read -r file; do
    # ID aus der JSON-Datei extrahieren
    id_value=$(jq -r '.id' "$file" 2>/dev/null)

    if [ -z "$id_value" ] || [ "$id_value" = "null" ]; then
        echo "Warnung: Kein 'id'-Attribut in '$file' gefunden."
        continue
    fi

    # Prüfen, ob die ID in der Liste existiert
    if [[ -n "${ID_TO_NAMES[$id_value]}" ]]; then
        # Englischen und deutschen Namen extrahieren
        IFS=':' read -r english_name german_name <<< "${ID_TO_NAMES[$id_value]}"

        # Standardmäßig: Deutscher Name (Englischer Name)
        new_name="$german_name ($english_name)"

        # Prüfen, ob der englische und deutsche Name gleich sind ODER die Länge > 30
        if [ "$english_name" = "$german_name" ] || [ ${#new_name} -gt 30 ]; then
            new_name="$german_name"  # Nur deutscher Name
        fi

        # JSON-Datei aktualisieren
        jq --arg new_name "$new_name" '.name = $new_name' "$file" > tmp.json && mv tmp.json "$file"

        echo "Aktualisiert: '$file' -> name = '$new_name'"
    else
        echo "Info: Kein Eintrag für ID '$id_value' in der Liste gefunden (Datei: '$file')."
    fi
done

echo "Skript abgeschlossen."
